function safeJson(value:unknown){
  return JSON.stringify(value).replace(/</g,'\\u003c').replace(/>/g,'\\u003e');
}

export function uiI18nClient(scope:UiScope):string{
  const dictionary=UI_DICTIONARIES[scope];
  return `
const UI_LANGUAGE_STORAGE='easy-local-mcp.ui-language';
const UI_DICTIONARY=${safeJson(dictionary)};
const UI_SOURCE_TO_KEY=Object.fromEntries(
  Object.entries(UI_DICTIONARY.en).map(([key,value])=>[value,key])
);
const uiResolveLanguage=()=>{
  const saved=localStorage.getItem(UI_LANGUAGE_STORAGE);
  if(saved==='en'||saved==='zh-CN')return saved;
  const preferred=(navigator.languages&&navigator.languages[0])||navigator.language||'en';
  return /^zh(?:-|$)/i.test(preferred)?'zh-CN':'en';
};
let uiLanguage=uiResolveLanguage();
const uiFormat=(value,vars={})=>String(value).replace(/\\{([a-zA-Z0-9_]+)\\}/g,(_,key)=>
  vars[key]===undefined?'{'+key+'}':String(vars[key])
);
window.uiT=(keyOrSource,vars={})=>{
  const key=UI_DICTIONARY.en[keyOrSource]!==undefined
    ? keyOrSource
    : UI_SOURCE_TO_KEY[keyOrSource];
  if(!key)return uiFormat(keyOrSource,vars);
  return uiFormat(
    UI_DICTIONARY[uiLanguage]?.[key]??UI_DICTIONARY.en[key]??keyOrSource,
    vars
  );
};
const uiTranslateTextNode=node=>{
  const raw=node.nodeValue||'';
  const source=raw.trim();
  const key=UI_SOURCE_TO_KEY[source];
  if(!source||!key)return;
  const translated=UI_DICTIONARY[uiLanguage]?.[key]??UI_DICTIONARY.en[key]??source;
  if(translated===source)return;
  const start=raw.indexOf(source);
  node.nodeValue=raw.slice(0,start)+translated+raw.slice(start+source.length);
};
const uiTranslateElement=element=>{
  for(const attribute of ['placeholder','aria-label','title','value']){
    const source=element.getAttribute?.(attribute);
    const key=source&&UI_SOURCE_TO_KEY[source];
    if(key){
      element.setAttribute(
        attribute,
        UI_DICTIONARY[uiLanguage]?.[key]??UI_DICTIONARY.en[key]??source
      );
    }
  }
};
window.uiApplyI18n=root=>{
  uiTranslateElement(root);
  const walker=document.createTreeWalker(
    root,
    NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT
  );
  let node=walker.currentNode;
  while(node){
    if(node.nodeType===Node.TEXT_NODE)uiTranslateTextNode(node);
    else if(node.nodeType===Node.ELEMENT_NODE)uiTranslateElement(node);
    node=walker.nextNode();
  }
};
document.documentElement.lang=uiLanguage;
const uiTitleKey=UI_SOURCE_TO_KEY[document.title];
if(uiTitleKey){
  document.title=UI_DICTIONARY[uiLanguage]?.[uiTitleKey]??UI_DICTIONARY.en[uiTitleKey]??document.title;
}
document.querySelectorAll('[data-ui-language]').forEach(selector=>{
  selector.value=uiLanguage;
  selector.addEventListener('change',()=>{
    const next=selector.value==='zh-CN'?'zh-CN':'en';
    localStorage.setItem(UI_LANGUAGE_STORAGE,next);
    location.reload();
  });
});
window.uiApplyI18n(document.body);
const uiI18nObserver=new MutationObserver(records=>{
  for(const record of records){
    if(record.type==='characterData'){
      uiTranslateTextNode(record.target);
      continue;
    }
    for(const node of record.addedNodes){
      if(node.nodeType===Node.TEXT_NODE)uiTranslateTextNode(node);
      else if(node.nodeType===Node.ELEMENT_NODE)window.uiApplyI18n(node);
    }
  }
});
uiI18nObserver.observe(document.body,{subtree:true,childList:true,characterData:true});
`;
}
